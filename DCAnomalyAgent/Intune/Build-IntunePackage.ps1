#Requires -Version 5.1
<#
.SYNOPSIS
    Builds the Intune scripts that turn on WinRM and/or install the push collector on
    endpoints. Intune runs them on the device as SYSTEM, pulled OUTBOUND from the cloud, so
    endpoint firewalls, blocked RPC, VLANs and off-network laptops don't matter.

.DESCRIPTION
    Intune platform scripts take no parameters and can't reach SYSVOL from home, so the output
    is self-contained: your settings are written into a header block and the repo's own
    scripts are embedded (base64) - Enable-EndpointWinRM.ps1, Install-PushCollector.ps1 and
    Send-InventoryCheckin.ps1. The device runs exactly the code every other install path runs.
    Re-run this after updating those scripts or rotating the token.

    Output (in -OutDir):
      Enable-ADAgentEndpoint.ps1     Platform script, OR the remediation script of a
                                     Remediation. Idempotent; logs to
                                     C:\ProgramData\AD-Agent\endpoint-setup.log; exits 1 on
                                     failure so Intune shows it as failed.
      Detect-ADAgentEndpoint.ps1     Remediation detection script: exit 1 if the tasks,
                                     collector or (if enabled) WinRM rule are missing.

    The output contains the collector token - it's written to Build\out\intune (git-ignored).
    Don't commit it.

.PARAMETER ServerUrl
    Jump server URL the collector posts to, e.g. 'http://jump-host:5000'.
.PARAMETER Token
    The jump server's COLLECTOR_TOKEN.
.PARAMETER InstallCollector
    Include the push collector install (default on).
.PARAMETER EnableWinRM
    Also turn WinRM on, scoped to -AllowedRemoteAddress.
.PARAMETER AllowedRemoteAddress
    Addresses WinRM is opened to (jump server IP, optional admin IPs/subnets).
.PARAMETER IntervalMinutes / FullInventoryAt
    Passed to Install-PushCollector.ps1.
.PARAMETER OutDir
    Output folder.

.EXAMPLE
    .\Build-IntunePackage.ps1 -ServerUrl 'http://jump-host:5000' -Token '<COLLECTOR_TOKEN>'
.EXAMPLE
    .\Build-IntunePackage.ps1 -ServerUrl 'http://jump-host:5000' -Token '<COLLECTOR_TOKEN>' `
        -EnableWinRM -AllowedRemoteAddress 10.15.2.21
#>
[CmdletBinding(PositionalBinding = $false)]
param(
    [Parameter(Mandatory)][string]$ServerUrl,
    [Parameter(Mandatory)][string]$Token,
    [bool]$InstallCollector = $true,
    [switch]$EnableWinRM,
    [string[]]$AllowedRemoteAddress,
    [int]$IntervalMinutes = 30,
    [string]$FullInventoryAt = '13:00',
    [string]$OutDir = (Join-Path (Split-Path -Parent (Split-Path -Parent $PSScriptRoot)) 'Build\out\intune')
)

$ErrorActionPreference = 'Stop'

if (-not $InstallCollector -and -not $EnableWinRM) { throw "Nothing to build - enable -InstallCollector and/or -EnableWinRM." }
$AllowedRemoteAddress = @($AllowedRemoteAddress | ForEach-Object { $_ -split ',' } | ForEach-Object { $_.Trim() } | Where-Object { $_ })
if ($EnableWinRM -and (-not $AllowedRemoteAddress -or ($AllowedRemoteAddress | Where-Object { $_ -in @('*', 'Any') }))) {
    throw "-EnableWinRM needs -AllowedRemoteAddress listing the jump server (not blank, '*' or 'Any')."
}
if ($ServerUrl -notmatch '^https?://') { throw "-ServerUrl must start with http:// or https://" }

# Certificates almost never list IP addresses, so an https:// URL with an IP fails every
# check-in with "Could not establish trust relationship". Warn now rather than at check-in.
try {
    $_u = [Uri]$ServerUrl; $_ip = $null
    if ($_u.Scheme -eq 'https' -and [Net.IPAddress]::TryParse($_u.DnsSafeHost, [ref]$_ip)) {
        Write-Warning "-ServerUrl uses the IP address '$($_u.DnsSafeHost)'. HTTPS check-ins will fail unless that IP is on the jump server's certificate - use the FQDN on the certificate instead (e.g. https://<jump FQDN>)."
    }
} catch { }
[void][datetime]::Parse($FullInventoryAt)

$collectorDir = Join-Path (Split-Path -Parent $PSScriptRoot) 'Collector'
function Get-Embedded([string]$Name) {
    $p = Join-Path $collectorDir $Name
    if (-not (Test-Path $p)) { throw "Missing $p" }
    # Read as UTF-8 explicitly (Windows PowerShell's default is the ANSI code page), and drop
    # '#Requires' lines - the text runs as a script block on the device, already as SYSTEM.
    $text = [IO.File]::ReadAllText($p, [Text.Encoding]::UTF8) -replace '(?m)^#Requires.*$', ''
    [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($text))
}
function ConvertTo-PsLiteral([string]$s) { "'" + ($s -replace "'", "''") + "'" }

$addrLiteral = if ($AllowedRemoteAddress) { '@(' + (($AllowedRemoteAddress | ForEach-Object { ConvertTo-PsLiteral $_ }) -join ', ') + ')' } else { '@()' }
$stamp = Get-Date -Format 'yyyy-MM-dd HH:mm'

$header = @"
# AD-Agent endpoint setup - GENERATED by Intune\Build-IntunePackage.ps1 on $stamp.
# Do not edit by hand: change the repo scripts or the build parameters and rebuild.
# Contains the collector token - keep it out of source control.
`$ServerUrl            = $(ConvertTo-PsLiteral $ServerUrl)
`$Token                = $(ConvertTo-PsLiteral $Token)
`$InstallCollector     = `$$($InstallCollector.ToString().ToLower())
`$EnableWinRM          = `$$($EnableWinRM.IsPresent.ToString().ToLower())
`$AllowedRemoteAddress = $addrLiteral
`$IntervalMinutes      = $IntervalMinutes
`$FullInventoryAt      = $(ConvertTo-PsLiteral $FullInventoryAt)
"@

$enableBody = @'

$ErrorActionPreference = 'Stop'
$baseDir = Join-Path $env:ProgramData 'AD-Agent'
$logPath = Join-Path $baseDir 'endpoint-setup.log'
function Write-SetupLog([string]$Message, [string]$Level = 'INFO') {
    $line = "[{0}] [{1}] [Intune] {2}" -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $Level, $Message
    Write-Output $line
    try {
        if (-not (Test-Path $baseDir)) { New-Item -ItemType Directory -Path $baseDir -Force | Out-Null }
        Add-Content -Path $logPath -Value $line -ErrorAction SilentlyContinue
    } catch { }
}
function Get-EmbeddedScript([string]$B64) {
    [scriptblock]::Create([Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($B64)))
}

# Intune can launch scripts in 32-bit PowerShell; the firewall/scheduled-task cmdlets need
# the native 64-bit host, so relaunch there if needed.
if ($env:PROCESSOR_ARCHITEW6432 -eq 'AMD64' -and $PSCommandPath) {
    & "$env:WINDIR\SysNative\WindowsPowerShell\v1.0\powershell.exe" -NoProfile -ExecutionPolicy Bypass -File $PSCommandPath
    exit $LASTEXITCODE
}

try {
    Write-SetupLog "Start (InstallCollector=$InstallCollector, EnableWinRM=$EnableWinRM)."
    if ($EnableWinRM) {
        & (Get-EmbeddedScript $WinRMB64) -AllowedRemoteAddress $AllowedRemoteAddress -LogPath $logPath | ForEach-Object { "$_" }
    }
    if ($InstallCollector) {
        $stage = Join-Path $baseDir 'setup'
        if (-not (Test-Path $stage)) { New-Item -ItemType Directory -Path $stage -Force | Out-Null }
        $src = Join-Path $stage 'Send-InventoryCheckin.ps1'
        [IO.File]::WriteAllText($src, [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($CollectorB64)), (New-Object Text.UTF8Encoding($true)))
        $out = & (Get-EmbeddedScript $InstallerB64) -ServerUrl $ServerUrl -Token $Token -SourcePath $src `
            -IntervalMinutes $IntervalMinutes -FullInventoryAt $FullInventoryAt *>&1 | ForEach-Object { "$_" }
        $out | ForEach-Object { Write-SetupLog $_ }
        if (-not (Get-ScheduledTask -TaskName 'AD-Agent Check-in' -ErrorAction SilentlyContinue)) {
            throw "Installer ran but the 'AD-Agent Check-in' task is not registered."
        }
    }
    Write-SetupLog 'Done.'
    exit 0
} catch {
    Write-SetupLog "Failed: $($_.Exception.Message)" 'ERROR'
    exit 1
}
'@

$detectBody = @'

# Exit 0 = compliant, 1 = needs remediation (Intune Remediations convention).
$problems = @()
if ($InstallCollector) {
    foreach ($t in @('AD-Agent Check-in', 'AD-Agent Full Inventory')) {
        if (-not (Get-ScheduledTask -TaskName $t -ErrorAction SilentlyContinue)) { $problems += "task '$t' missing" }
    }
    if (-not (Test-Path (Join-Path $env:ProgramData 'AD-Agent\Send-InventoryCheckin.ps1'))) { $problems += 'collector script missing' }
    $task = Get-ScheduledTask -TaskName 'AD-Agent Check-in' -ErrorAction SilentlyContinue
    if ($task) {
        $action = @($task.Actions)[0]
        if ($action.Arguments -notlike "*$ServerUrl*") { $problems += 'check-in task points at a different server URL' }
    }
}
if ($EnableWinRM) {
    $svc = Get-Service -Name WinRM -ErrorAction SilentlyContinue
    if (-not $svc -or $svc.Status -ne 'Running') { $problems += 'WinRM service not running' }
    if (-not (Get-NetFirewallRule -Name 'ADAgent-WinRM-In' -ErrorAction SilentlyContinue)) { $problems += 'WinRM firewall rule missing' }
}
if ($problems) {
    Write-Output ("Needs remediation: " + ($problems -join '; '))
    exit 1
}
Write-Output 'AD-Agent endpoint setup present.'
exit 0
'@

$embeds = @"

`$WinRMB64     = '$(if ($EnableWinRM) { Get-Embedded 'Enable-EndpointWinRM.ps1' })'
`$InstallerB64 = '$(if ($InstallCollector) { Get-Embedded 'Install-PushCollector.ps1' })'
`$CollectorB64 = '$(if ($InstallCollector) { Get-Embedded 'Send-InventoryCheckin.ps1' })'
"@

if (-not (Test-Path $OutDir)) { New-Item -ItemType Directory -Path $OutDir -Force | Out-Null }
$enablePath = Join-Path $OutDir 'Enable-ADAgentEndpoint.ps1'
$detectPath = Join-Path $OutDir 'Detect-ADAgentEndpoint.ps1'
# UTF-8 with BOM: what Windows PowerShell 5.1 (the Intune agent's host) reads reliably.
$utf8Bom = New-Object Text.UTF8Encoding($true)
[IO.File]::WriteAllText($enablePath, $header + $embeds + $enableBody, $utf8Bom)
[IO.File]::WriteAllText($detectPath, $header + $detectBody, $utf8Bom)

# Intune's limit for platform/remediation scripts is 200 KB.
foreach ($p in @($enablePath, $detectPath)) {
    $kb = [math]::Round((Get-Item $p).Length / 1KB, 1)
    if ($kb -gt 200) { throw "$p is $kb KB - over Intune's 200 KB script limit." }
    Write-Host ("Wrote {0} ({1} KB)" -f $p, $kb)
}

Write-Host ""
Write-Host "Intune admin center > Devices > Scripts and remediations:" -ForegroundColor Green
Write-Host "  Platform scripts (one-shot): add Enable-ADAgentEndpoint.ps1"
Write-Host "     Run using logged-on credentials = No | Enforce signature check = No | Run in 64-bit = Yes"
Write-Host "  OR Remediations (self-healing, needs Windows Enterprise E3/E5 or equivalent):"
Write-Host "     Detection = Detect-ADAgentEndpoint.ps1, Remediation = Enable-ADAgentEndpoint.ps1"
Write-Host "     Run as logged-on user = No | 64-bit = Yes | schedule e.g. daily"
Write-Host "  Assign to a 1-device test group first. Then check C:\ProgramData\AD-Agent\endpoint-setup.log"
Write-Host "  on the device and the Endpoints page on the jump server."
Write-Host ""
Write-Host "These files contain the collector token. Keep them out of git (Build\out is ignored)." -ForegroundColor Yellow
